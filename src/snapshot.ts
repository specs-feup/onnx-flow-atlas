import fs from "fs";
import path from "path";
import { graphviz } from "node-graphviz";
import { BUILTIN_PROFILES } from "./types.js";
import { RecipeGraphAnalyzer } from "./RecipeGraphAnalyzer.js";
import { DynamicProbeVerifier } from "./DynamicProbeVerifier.js";
import { DotFormatter } from "./formatters/DotFormatter.js";
import { MarkdownReporter } from "./formatters/MarkdownReporter.js";

async function renderDotAndSvg(basePath: string, dotContent: string): Promise<void> {
    fs.writeFileSync(`${basePath}.dot`, dotContent, "utf8");
    const svgContent = await graphviz.layout(dotContent, "svg", "dot");
    fs.writeFileSync(`${basePath}.svg`, svgContent, "utf8");
}

export async function generateFullSnapshot(outDir: string = "atlas"): Promise<void> {
    const treesDir = path.join(outDir, "trees");
    fs.rmSync(treesDir, { recursive: true, force: true });
    fs.mkdirSync(treesDir, { recursive: true });

    console.log(`[Snapshot] Initializing analyzer and running dynamic recipe probes...`);
    const analyzer = new RecipeGraphAnalyzer();
    const recipes = analyzer.loadRecipes();

    // Run dynamic verification across BOTH canonicalization and loop-lowering recipes
    const verifier = new DynamicProbeVerifier();
    verifier.verifyAllRecipes(recipes);

    // 1. Analyze Scalar CGRA Profile (Primary)
    console.log(`[Snapshot] Generating Scalar-CGRA full report & maps...`);
    const cgraProfile = BUILTIN_PROFILES["scalar-cgra"];
    const cgraReport = analyzer.analyze(cgraProfile, recipes);

    fs.writeFileSync(
        path.join(outDir, "01_cgra_full_report.md"),
        MarkdownReporter.generateReport(cgraReport),
        "utf8",
    );

    await renderDotAndSvg(
        path.join(outDir, "01_cgra_full_atlas"),
        DotFormatter.toDot(cgraReport, { includeLoopLowering: true }),
    );

    // 2. Pure Algebraic Canonicalization Map (No Loop Lowering)
    console.log(`[Snapshot] Generating Canonicalization-only map...`);
    await renderDotAndSvg(
        path.join(outDir, "02_canonicalization_only"),
        DotFormatter.toDot(cgraReport, { includeLoopLowering: false }),
    );

    // 3. Analyze Vector-DSP Profile (Comparison)
    console.log(`[Snapshot] Generating Vector-DSP comparison report & map...`);
    const dspProfile = BUILTIN_PROFILES["vector-dsp"];
    const dspReport = analyzer.analyze(dspProfile, recipes);

    fs.writeFileSync(
        path.join(outDir, "03_vector_dsp_report.md"),
        MarkdownReporter.generateReport(dspReport),
        "utf8",
    );

    await renderDotAndSvg(
        path.join(outDir, "03_vector_dsp_atlas"),
        DotFormatter.toDot(dspReport, { includeLoopLowering: true }),
    );

    console.log(`[Snapshot] Generating emergent abstraction hierarchy maps...`);
    await renderDotAndSvg(
        path.join(outDir, "04_cgra_abstraction_hierarchy"),
        DotFormatter.toDot(cgraReport, { groupByLevel: true }),
    );
    await renderDotAndSvg(
        path.join(outDir, "05_vector_dsp_abstraction_hierarchy"),
        DotFormatter.toDot(dspReport, { groupByLevel: true }),
    );

    // 4. Generate Per-Operator Lowering Trees & Text Breakdowns for ALL Decomposable Ops
    const decomposableOps = Array.from(cgraReport.operators.values())
        .filter((o) => o.atlasDetail !== undefined)
        .map((o) => o.opType)
        .sort();

    console.log(
        `[Snapshot] Rendering ${decomposableOps.length} per-operator lowering trees & breakdowns...`,
    );
    for (const op of decomposableOps) {
        const opDot = DotFormatter.toDot(cgraReport, {
            rootOp: op,
            includeLoopLowering: true,
        });
        await renderDotAndSvg(path.join(treesDir, op), opDot);

        const opInfo = cgraReport.operators.get(op)!;
        if (opInfo.atlasDetail) {
            const mdLines = [
                `# \`${op}\` — Decomposition & Scalar Lowering Atlas`,
                ``,
                `[← Back to Atlas Index](../README.md)`,
                ``,
                `![${op} Lowering Tree](./${op}.svg)`,
                ``,
                ...MarkdownReporter.renderOperatorDetail(opInfo.atlasDetail),
            ];
            fs.writeFileSync(path.join(treesDir, `${op}.md`), mdLines.join("\n"), "utf8");
        }
    }

    // 5. Generate Master Index (atlas/README.md) for instant GitHub browsing
    const indexLines: string[] = [
        `# ONNX-Flow Decomposition Snapshot`,
        ``,
        `*Auto-generated by \`onnx-flow-atlas\`.*`,
        ``,
        `## Global Reports & Maps`,
        `- [**Scalar-CGRA Full Analysis & Gap Report**](./01_cgra_full_report.md) ([Full SVG Map](./01_cgra_full_atlas.svg) | [DOT](./01_cgra_full_atlas.dot))`,
        `- [**Algebraic Canonicalization Map (No Loops)**](./02_canonicalization_only.svg) ([DOT](./02_canonicalization_only.dot))`,
        `- [**Vector-DSP Comparison Report**](./03_vector_dsp_report.md) ([Full SVG Map](./03_vector_dsp_atlas.svg) | [DOT](./03_vector_dsp_atlas.dot))`,
        `- [**Scalar-CGRA Emergent Abstraction Hierarchy**](./04_cgra_abstraction_hierarchy.svg) ([DOT](./04_cgra_abstraction_hierarchy.dot))`,
        `- [**Vector-DSP Emergent Abstraction Hierarchy**](./05_vector_dsp_abstraction_hierarchy.svg) ([DOT](./05_vector_dsp_abstraction_hierarchy.dot))`,
        ``,
        `## Per-Operator Lowering Atlas (${decomposableOps.length} Decomposable Operators)`,
        `| Operator | Level | Status (\`scalar-cgra\`) | Scalar (\`0D\`) Readiness | Shape Support | Best \`0D\` Ratio | Max Depth | Blocking Gaps | Breakdown & Tree |`,
        `| :--- | :---: | :--- | :--- | :---: | :---: | :---: | :--- | :---: |`,
    ];

    for (const op of decomposableOps) {
        const info = cgraReport.operators.get(op)!;
        const detail = info.atlasDetail!;
        const ratioPct = `${(detail.bestScalarComputeRatio * 100).toFixed(0)}%`;
        const shapeCol = info.bestShapeSupport ?? "—";
        const gaps = info.blockingLeafGaps.map((g) => `\`${g}\``).join(", ") || "None";

        const lvl = info.hierarchyMetrics?.level;
        const lvlCell = lvl !== undefined && lvl >= 0 ? `**L${lvl}**` : "Gap";
        
        indexLines.push(
            `| \`${op}\` | ${lvlCell} | **${info.status}** | ${detail.scalarReadiness} | ${shapeCol} | **${ratioPct}** | ${info.maxLoweringDepth} | ${gaps} | [Text](./trees/${op}.md) · [SVG](./trees/${op}.svg) · [DOT](./trees/${op}.dot) |`,
        );
    }

    fs.writeFileSync(path.join(outDir, "README.md"), indexLines.join("\n"), "utf8");
    console.log(
        `[Snapshot] Complete! All artifacts written to ./${outDir}/ (open ./${outDir}/README.md)`,
    );
}

// Run if invoked directly
const targetDir = process.argv[2] ?? "atlas";
generateFullSnapshot(targetDir).catch((err) => {
    console.error("[Snapshot] Failed:", err);
    process.exit(1);
});